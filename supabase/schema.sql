-- Eissa Store schema. Run in Supabase SQL Editor on a NEW project.
create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 role text not null default 'customer' check (role in ('owner','admin','staff','customer')),
 created_at timestamptz not null default now()
);
create table if not exists public.categories (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 image_url text,
 sort_order int not null default 0,
 created_at timestamptz not null default now()
);
create table if not exists public.products (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 description text,
 price numeric(12,2) not null check(price >= 0),
 compare_at_price numeric(12,2),
 image_url text,
 category_id uuid references public.categories(id) on delete set null,
 stock int not null default 0 check(stock >= 0),
 is_active boolean not null default true,
 is_custom boolean not null default false,
 variants jsonb not null default '{}'::jsonb,
 custom_fields jsonb not null default '[]'::jsonb,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(),
 order_number bigint generated by default as identity unique,
 customer_name text not null,
 phone text not null,
 address text not null,
 notes text,
 payment_method text not null default 'الدفع عند الاستلام',
 status text not null default 'new' check(status in ('new','confirmed','processing','shipped','completed','cancelled')),
 total numeric(12,2) not null check(total >= 0),
 items jsonb not null default '[]'::jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.shipping_methods (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 fee numeric(12,2) not null default 0,
 region text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.payment_methods (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 instructions text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create index if not exists products_active_idx on public.products(is_active);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_phone_idx on public.orders(phone);
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.shipping_methods enable row level security;
alter table public.payment_methods enable row level security;
-- Role check is based on profiles. Customers cannot read orders or manage catalog.
create or replace function public.is_store_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role in ('owner','admin','staff')) $$;
create policy "profiles read self or admin" on public.profiles for select using (id=auth.uid() or public.is_store_admin());
create policy "admins manage profiles" on public.profiles for all using (public.is_store_admin()) with check (public.is_store_admin());
create policy "public read categories" on public.categories for select using (true);
create policy "admins manage categories" on public.categories for all using (public.is_store_admin()) with check (public.is_store_admin());
create policy "public read active products" on public.products for select using (is_active=true or public.is_store_admin());
create policy "admins manage products" on public.products for all using (public.is_store_admin()) with check (public.is_store_admin());
create policy "public create orders" on public.orders for insert with check (true);
create policy "admins read orders" on public.orders for select using (public.is_store_admin());
create policy "admins update orders" on public.orders for update using (public.is_store_admin()) with check (public.is_store_admin());
create policy "admins manage shipping" on public.shipping_methods for all using (public.is_store_admin()) with check (public.is_store_admin());
create policy "public read active payment methods" on public.payment_methods for select using (active=true or public.is_store_admin());
create policy "admins manage payment methods" on public.payment_methods for all using (public.is_store_admin()) with check (public.is_store_admin());
